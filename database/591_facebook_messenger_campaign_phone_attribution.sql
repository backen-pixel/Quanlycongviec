CREATE TABLE IF NOT EXISTS facebook_ad_campaign_mappings (
  fb_ad_id TEXT PRIMARY KEY,
  ad_account_id TEXT NOT NULL,
  page_id TEXT NOT NULL,
  campaign_id TEXT NOT NULL,
  campaign_name TEXT,
  updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS idx_fb_ad_campaign_mappings_campaign
  ON facebook_ad_campaign_mappings (campaign_id);

CREATE TABLE IF NOT EXISTS facebook_messenger_ad_attributions (
  id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  contact_id UUID NOT NULL REFERENCES facebook_contacts(id) ON DELETE CASCADE,
  page_id TEXT NOT NULL,
  fb_ad_id TEXT NOT NULL,
  campaign_id TEXT,
  referral_source TEXT,
  referral_type TEXT,
  referral JSONB NOT NULL DEFAULT '{}'::jsonb,
  attributed_at TIMESTAMPTZ NOT NULL,
  fb_event_timestamp_ms BIGINT NOT NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  UNIQUE (contact_id, page_id, fb_ad_id, fb_event_timestamp_ms)
);

CREATE INDEX IF NOT EXISTS idx_fb_msg_attr_contact_time
  ON facebook_messenger_ad_attributions (contact_id, attributed_at DESC);
CREATE INDEX IF NOT EXISTS idx_fb_msg_attr_campaign_time
  ON facebook_messenger_ad_attributions (campaign_id, attributed_at DESC);

ALTER TABLE facebook_messages
  ADD COLUMN IF NOT EXISTS facebook_occurred_at TIMESTAMPTZ,
  ADD COLUMN IF NOT EXISTS detected_phone TEXT;

CREATE INDEX IF NOT EXISTS idx_fb_messages_detected_phone_time
  ON facebook_messages (facebook_occurred_at DESC, contact_id)
  WHERE direction = 'inbound' AND detected_phone IS NOT NULL;
